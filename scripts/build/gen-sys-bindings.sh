#!/usr/bin/env bash
# Generate src/sys/bindings.rs — Rust declarations for the SDK C ABI — from a
# staged kit's headers. Committed output, like src/account/console_contract.rs:
# regenerate when the kit pin moves, never hand-edit.
#
#   scripts/build/gen-sys-bindings.sh [--check] [kit-prefix]
#
# One file serves every target. Generated per target (2026-09-24, kit 0.20.37)
# the outputs differ only in C enum signedness — `c_uint` from clang on Apple and
# Linux, `c_int` from MSVC — which is ABI-identical for these non-negative
# 32-bit values, and in `va_list`, which only rac_logger_logv uses; it is
# blocked here. Struct layouts are asserted at compile time on every target.
#
# The kit's RAC_*_DEFAULT option/config structs are header-only `static const`
# values: bindgen would declare them as extern statics that exist in no kit
# archive, so a use compiles and then fails to link. They are blocked; build the
# struct from the header's literal defaults where it is needed.
#
# Needs bindgen-cli (`cargo install bindgen-cli`) and libclang. --check exits 1
# when the committed file differs from what the kit produces. The kit defaults
# to WALLY_SDK_KIT, then .deps/kit (CMake's auto-fetch location).
set -euo pipefail
ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)"
CHECK=0
if [[ "${1:-}" == "--check" ]]; then CHECK=1; shift; fi
KIT="${1:-${WALLY_SDK_KIT:-${ROOT}/.deps/kit}}"
[[ -d "${KIT}/include/rac" ]] || { echo "error: no kit headers at ${KIT}/include/rac" >&2; exit 2; }
command -v bindgen >/dev/null || { echo "error: bindgen not found (cargo install bindgen-cli)" >&2; exit 2; }

version="$(cat "${KIT}/share/runanywhere/VERSION" 2>/dev/null || echo unknown)"
out="$(mktemp)"
trap 'rm -f "${out}"' EXIT
{
    echo "// @generated by scripts/build/gen-sys-bindings.sh from RunAnywhere kit ${version}."
    echo "// DO NOT EDIT. Regenerate after a kit pin bump."
    bindgen "${ROOT}/scripts/build/sys-bindings.h" \
        --allowlist-function 'rac_.*' --allowlist-type 'rac_.*' --allowlist-var 'RAC_.*' \
        --blocklist-function 'rac_logger_logv' --blocklist-type 'va_list|__builtin_va_list|__va_list_tag' \
        --blocklist-var 'RAC_LOG_(DEBUG|INFO|WARNING|ERROR)' \
        --blocklist-var 'RAC_.*_DEFAULT' \
        --default-enum-style consts --no-prepend-enum-name \
        --rust-target 1.82 --merge-extern-blocks --sort-semantically --clang-macro-fallback \
        -- -I"${KIT}/include" -x c -std=c11
} > "${out}"
dest="${ROOT}/src/sys/bindings.rs"
if [[ "${CHECK}" -eq 1 ]]; then
    if ! diff -q "${out}" "${dest}" >/dev/null; then
        echo "src/sys/bindings.rs is stale for kit ${version}; run scripts/build/gen-sys-bindings.sh" >&2
        exit 1
    fi
    echo "src/sys/bindings.rs matches kit ${version}"
else
    cp "${out}" "${dest}"
    echo "wrote src/sys/bindings.rs from kit ${version}"
fi
